const interpolate = (template: string, params?: Record<string, string | number>): string => {
  if (!params) {
    return template;
  }

  return Object.entries(params).reduce((result, [key, value]) => result.replace(`{{${key}}}`, String(value)), template);
};

const translate = (scope: Record<Locale, Dictionary>, locale: string, key: string, fallback?: string, params?: Record<string, string | number>): string => {
  const normalized: Locale = locale === 'am' || locale === 'ti' ? locale : 'en';
  const value = scope[normalized]?.[key] || scope.en[key] || fallback || key;
  return interpolate(value, params);
};

export const useAdminI18n = () => {
  const { lang } = useLanguage();
  return useMemo(() => {
    const translator = (key: string, fallback?: string, params?: Record<string, string | number>) =>
      translate(adminDictionary, lang, key, fallback, params);
    return Object.assign(translator, { tAdmin: translator });
  }, [lang]);
};

export const usePublicUiI18n = () => {
  const { lang } = useLanguage();
  return useMemo(() => {
    const tPublicUi = (key: string, fallback?: string, params?: Record<string, string | number>) =>
      translate(publicDictionary, lang, key, fallback, params);
    const tAdmin = (key: string, fallback?: string, params?: Record<string, string | number>) =>
      translate(adminDictionary, lang, key, fallback, params);
    return Object.assign(tPublicUi, { tPublic: tPublicUi, tPublicUi, tAdmin });
  }, [lang]);
};
